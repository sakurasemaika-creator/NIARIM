    ? words.layerPanelDefaultLayerName(1)
    : layer.name;

/// These are display names. Saved names remain the input to the procedural
/// texture engine and keep their meaning when a project changes hands.
String creativePresetLabel(
  AppLocalizations words,
  String savedName, {
  required bool builtIn,
}) {
  if (!builtIn) return savedName;
  final locale = words.localeName;
  final language = locale.startsWith('zh_Hant')
      ? 'zh_Hant'
      : locale.split('_').first;
  final languageIndex = _languages.indexOf(language);
  if (languageIndex < 0) return savedName;

  String? translate(String name) => _labels[name]?[languageIndex];
  final exact = translate(savedName);
  if (exact != null) return exact;

  final percentage = _percentage.firstMatch(savedName);
  if (percentage != null) {
    final label = translate(percentage[1]!);
    if (label != null) return '$label ${percentage[2]}%';
  }
  final denier = _denier.firstMatch(savedName);
  if (denier != null) {
    final label = translate(denier[1]!);
    if (label != null) return '$label ${denier[2]}D';
  }
  final dither = _dither.firstMatch(savedName);
  if (dither != null) {
    return '${translate('ピクセルディザ')} (${dither[1]}, ${dither[2]}%)';
  }
  return savedName;
}

