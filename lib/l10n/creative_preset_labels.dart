final _percentage = RegExp(r'^(網点|ピクセル砂目) (\d+)%$');
final _denier = RegExp(r'^(ストッキング|タイツ) (\d+)デニール$');
final _dither = RegExp(r'^ピクセルディザ（[^・]+・(\d+×\d+)・(\d+)%）$');

