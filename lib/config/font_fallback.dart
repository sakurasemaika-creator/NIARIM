/// アプリで使うフォントの「未収録文字を補う代替フォント」の定義。
///
/// 同梱フォントはいずれも既存フォントを改変したものだが、改変の過程で
/// 収録文字が減っているものがあり、未収録の文字はそのままだと豆腐（□）で
/// 表示されてしまう。そこで**それぞれの改変元フォントで補う**。
///
/// 各フォントのcmapテーブルを直接数えた実測値：
///
/// | フォント | 収録文字数 | 位置づけ |
/// |---|---|---|
/// | 白光明朝（本文用） | 16,726 | Noto Serif JP派生 |
/// | Noto Serif JP | 16,726 | 白光明朝の改変元 |
/// | くらむぼん（見出し用） | 8,262 | Dela Gothic One派生 |
/// | Dela Gothic One | 9,030 | くらむぼんの改変元 |
///
/// ここから分かること：
///
/// - **白光明朝とNoto Serif JPは収録文字が完全に一致している**（差分0文字）。
///   つまり白光明朝が取りこぼす文字はNoto Serif JPにも無く、この組み合わせ
///   では補える文字が存在しない。
/// - **くらむぼんはDela Gothic Oneより1,456文字少ない**。ここは改変元で
///   実際に補える。さらにNoto Serif JPを続ければ計8,533文字を補える。
/// - Dela Gothic OneにはNoto Serif JPに無い254文字（Ą ć Č İ 等の拡張
///   ラテン）が含まれる。白光明朝が取りこぼす文字は**ちょうどこの254文字
///   だけ**なので、本文側にDela Gothic Oneを先頭で置いても、
///   「セリフ体で出せる文字がゴシック体になる」ことは起こらない
///   （Noto Serif JPが持つ文字は白光明朝も必ず持っているため、
///   そもそもフォールバックが発火しない）。
///
/// この性質があるため、本文用・見出し用で同じ並び（Dela Gothic One →
/// Noto Serif JP）を共有できる。共有できることには実務上の意味があり、
/// `TextStyle(fontFamily: 'Kuramubon')`のようにコード中で直接フォントを
/// 指定している箇所（アプリ全体で187箇所）は、`fontFamilyFallback`を
/// 個別に書かなくても**祖先のテキストスタイルからfontFamilyFallbackを
/// 継承する**。したがってテーマ側の並びを揃えておけば、187箇所すべてが
/// 自動的に「まず改変元のDela Gothic One、それでも無ければNoto Serif JP」
/// で補われる。
library;

/// アプリ全体で共有する代替フォント列（本文・見出し共通）。
///
/// 改変元を先に置くのは、字形の印象が近く混植したときの違和感が
/// 小さいため。
const List<String> kAppFontFallback = <String>[
  'DelaGothicOne',
  'NotoSerifJP',
];
